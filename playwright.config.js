import os from 'os';

/**
 * Calculate optimal number of workers based on system resources
 * For Docker environments, we use slightly fewer workers than available cores
 * to avoid resource contention
 */
const calculateWorkers = () => {
  const cpuCount = os.cpus().length;
  // Use 70% of available cores, but always at least 2 if possible
  const optimal = Math.max(2, Math.floor(cpuCount * 0.7));

  // In CI, we're more conservative with resources
  return process.env.CI ? Math.min(4, optimal) : optimal;
};

